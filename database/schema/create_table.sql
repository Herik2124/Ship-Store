-- 4. PURCHASE ORDER TABLES
--------------------------------------------------------------------------------

CREATE TABLE TEAM_03_PURCHASE_ORDER (
    PO_ID                     NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1) PRIMARY KEY,
    PO_NO                     VARCHAR2(30)  NOT NULL,
    DEMAND_ID                 NUMBER        NOT NULL,
    QUOTATION_ID              NUMBER        NOT NULL,
    VENDOR_ID                 NUMBER        NOT NULL,
    CREATED_BY_USER_ID        NUMBER        NOT NULL,
    PO_DATE                   DATE DEFAULT SYSDATE NOT NULL,
    EXPECTED_DELIVERY_DATE    DATE          NOT NULL,
    DELIVERY_LOCATION         VARCHAR2(250) NOT NULL,
    CURRENCY_CODE             VARCHAR2(3)   NOT NULL,
    SUBTOTAL_AMOUNT           NUMBER(14,2)  NOT NULL,
    DELIVERY_CHARGE           NUMBER(14,2) DEFAULT 0 NOT NULL,
    TAX_AMOUNT                NUMBER(14,2) DEFAULT 0 NOT NULL,
    TOTAL_AMOUNT              NUMBER(14,2)  NOT NULL,
    PAYMENT_TERMS             VARCHAR2(1000),
    PO_STATUS                 VARCHAR2(30) DEFAULT 'PENDING' NOT NULL,
    CREATED_AT                TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT                TIMESTAMP,
    CONSTRAINT UK_03_PO_NO UNIQUE (PO_NO),
    CONSTRAINT UK_03_PO_DEMAND UNIQUE (DEMAND_ID),
    CONSTRAINT UK_03_PO_QUOTATION UNIQUE (QUOTATION_ID),
    CONSTRAINT FK_03_PO_DEMAND FOREIGN KEY (DEMAND_ID)
        REFERENCES TEAM_03_DEMAND (DEMAND_ID),
    CONSTRAINT FK_03_PO_QUOTATION FOREIGN KEY (QUOTATION_ID)
        REFERENCES TEAM_03_QUOTATION (QUOTATION_ID),
    CONSTRAINT FK_03_PO_VENDOR FOREIGN KEY (VENDOR_ID)
        REFERENCES TEAM_03_VENDOR (VENDOR_ID),
    CONSTRAINT FK_03_PO_CREATED_BY FOREIGN KEY (CREATED_BY_USER_ID)
        REFERENCES TEAM_03_APP_USER (USER_ID),
    CONSTRAINT CK_03_PO_STATUS CHECK
        (PO_STATUS IN (
            'PENDING', 'CONFIRMED', 'PACKED', 'DISPATCHED',
            'PARTIALLY_DELIVERED', 'DELIVERED', 'DELAYED', 'CANCELLED'
        )),
    CONSTRAINT CK_03_PO_AMOUNTS CHECK
        (SUBTOTAL_AMOUNT >= 0 AND DELIVERY_CHARGE >= 0 AND TAX_AMOUNT >= 0
         AND TOTAL_AMOUNT >= 0)
);

CREATE TABLE TEAM_03_PURCHASE_ORDER_LINE (
    PO_LINE_ID               NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1) PRIMARY KEY,
    PO_ID                    NUMBER       NOT NULL,
    QUOTATION_LINE_ID        NUMBER       NOT NULL,
    ITEM_ID                  NUMBER       NOT NULL,
    ORDERED_QTY              NUMBER(12,2) NOT NULL,
    UNIT_OF_MEASURE          VARCHAR2(20) NOT NULL,
    UNIT_PRICE               NUMBER(14,2) NOT NULL,
    LINE_TOTAL               NUMBER(14,2) NOT NULL,
    CONSTRAINT UK_03_PO_ITEM UNIQUE (PO_ID, ITEM_ID),
    CONSTRAINT UK_03_PO_QUOTE_LINE UNIQUE (QUOTATION_LINE_ID),
    CONSTRAINT FK_03_PO_LINE_HEADER FOREIGN KEY (PO_ID)
        REFERENCES TEAM_03_PURCHASE_ORDER (PO_ID),
    CONSTRAINT FK_03_PO_LINE_QUOTE FOREIGN KEY (QUOTATION_LINE_ID)
        REFERENCES TEAM_03_QUOTATION_LINE (QUOTATION_LINE_ID),
    CONSTRAINT FK_03_PO_LINE_ITEM FOREIGN KEY (ITEM_ID)
        REFERENCES TEAM_03_ITEM (ITEM_ID),
    CONSTRAINT CK_03_PO_LINE_VALUES CHECK
        (ORDERED_QTY > 0 AND UNIT_PRICE >= 0 AND LINE_TOTAL >= 0)
);


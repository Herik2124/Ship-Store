-- 3. QUOTATION TABLES
--------------------------------------------------------------------------------

CREATE TABLE TEAM_03_QUOTATION (
    QUOTATION_ID             NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1) PRIMARY KEY,
    QUOTATION_NO             VARCHAR2(30) NOT NULL,
    RFQ_VENDOR_ID            NUMBER       NOT NULL,
    QUOTATION_DATE           DATE DEFAULT SYSDATE NOT NULL,
    VALID_UNTIL              DATE         NOT NULL,
    CURRENCY_CODE            VARCHAR2(3) DEFAULT 'USD' NOT NULL,
    EXPECTED_DELIVERY_DATE   DATE         NOT NULL,
    DELIVERY_CHARGE          NUMBER(14,2) DEFAULT 0 NOT NULL,
    TAX_AMOUNT               NUMBER(14,2) DEFAULT 0 NOT NULL,
    TOTAL_AMOUNT             NUMBER(14,2) NOT NULL,
    PAYMENT_TERMS            VARCHAR2(1000),
    TERMS_CONDITIONS         VARCHAR2(2000),
    QUOTATION_STATUS         VARCHAR2(20) DEFAULT 'DRAFT' NOT NULL,
    SUBMITTED_AT             TIMESTAMP,
    CREATED_AT               TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT               TIMESTAMP,
    CONSTRAINT UK_03_QUOTATION_NO UNIQUE (QUOTATION_NO),
    CONSTRAINT UK_03_QUOTATION_RFQ UNIQUE (RFQ_VENDOR_ID),
    CONSTRAINT FK_03_QUOTATION_RFQ FOREIGN KEY (RFQ_VENDOR_ID)
        REFERENCES TEAM_03_RFQ_VENDOR (RFQ_VENDOR_ID),
    CONSTRAINT CK_03_QUOTATION_STATUS CHECK
        (QUOTATION_STATUS IN (
            'DRAFT', 'SUBMITTED', 'SELECTED', 'REJECTED', 'EXPIRED', 'WITHDRAWN'
        )),
    CONSTRAINT CK_03_QUOTATION_AMOUNTS CHECK
        (DELIVERY_CHARGE >= 0 AND TAX_AMOUNT >= 0 AND TOTAL_AMOUNT >= 0)
);

CREATE TABLE TEAM_03_QUOTATION_LINE (
    QUOTATION_LINE_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1) PRIMARY KEY,
    QUOTATION_ID             NUMBER       NOT NULL,
    DEMAND_LINE_ID           NUMBER       NOT NULL,
    AVAILABLE_QTY            NUMBER(12,2) NOT NULL,
    UNIT_PRICE               NUMBER(14,2) NOT NULL,
    TAX_PERCENT              NUMBER(5,2) DEFAULT 0 NOT NULL,
    LINE_TOTAL               NUMBER(14,2) NOT NULL,
    EXPECTED_DELIVERY_DATE   DATE,
    REMARKS                  VARCHAR2(1000),
    CONSTRAINT UK_03_QUOTE_DEMAND_LINE UNIQUE (QUOTATION_ID, DEMAND_LINE_ID),
    CONSTRAINT FK_03_QUOTE_LINE_HEADER FOREIGN KEY (QUOTATION_ID)
        REFERENCES TEAM_03_QUOTATION (QUOTATION_ID),
    CONSTRAINT FK_03_QUOTE_LINE_DEMAND FOREIGN KEY (DEMAND_LINE_ID)
        REFERENCES TEAM_03_DEMAND_LINE (DEMAND_LINE_ID),
    CONSTRAINT CK_03_QUOTE_LINE_VALUES CHECK
        (AVAILABLE_QTY >= 0 AND UNIT_PRICE >= 0 AND TAX_PERCENT BETWEEN 0 AND 100
         AND LINE_TOTAL >= 0)
);


-- 2. DEMAND AND REQUEST-FOR-QUOTATION TABLES
--------------------------------------------------------------------------------

CREATE TABLE TEAM_03_DEMAND (
    DEMAND_ID               NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1) PRIMARY KEY,
    DEMAND_NO               VARCHAR2(30)  NOT NULL,
    SHIP_ID                 NUMBER        NOT NULL,
    CREATED_BY_USER_ID      NUMBER        NOT NULL,
    REQUIRED_DELIVERY_DATE  DATE          NOT NULL,
    DELIVERY_LOCATION       VARCHAR2(250) NOT NULL,
    INSTRUCTIONS            VARCHAR2(2000),
    DEMAND_STATUS           VARCHAR2(30) DEFAULT 'DRAFT' NOT NULL,
    RAISED_DATE             TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    SELECTED_DATE           TIMESTAMP,
    CLOSED_DATE             TIMESTAMP,
    UPDATED_AT              TIMESTAMP,
    CONSTRAINT UK_03_DEMAND_NO UNIQUE (DEMAND_NO),
    CONSTRAINT FK_03_DEMAND_SHIP FOREIGN KEY (SHIP_ID)
        REFERENCES TEAM_03_SHIP (SHIP_ID),
    CONSTRAINT FK_03_DEMAND_CREATED_BY FOREIGN KEY (CREATED_BY_USER_ID)
        REFERENCES TEAM_03_APP_USER (USER_ID),
    CONSTRAINT CK_03_DEMAND_STATUS CHECK
        (DEMAND_STATUS IN (
            'DRAFT', 'SUBMITTED', 'RFQ_OPEN', 'QUOTATIONS_RECEIVED',
            'VENDOR_SELECTED', 'ORDER_CREATED', 'PARTIALLY_DELIVERED',
            'DELIVERED', 'CLOSED', 'CANCELLED'
        ))
);

CREATE TABLE TEAM_03_DEMAND_LINE (
    DEMAND_LINE_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1) PRIMARY KEY,
    DEMAND_ID             NUMBER        NOT NULL,
    ITEM_ID               NUMBER        NOT NULL,
    REQUESTED_QTY         NUMBER(12,2)  NOT NULL,
    UNIT_OF_MEASURE       VARCHAR2(20)  NOT NULL,
    ITEM_SPECIFICATION    VARCHAR2(1000),
    REMARKS               VARCHAR2(1000),
    CONSTRAINT UK_03_DEMAND_ITEM UNIQUE (DEMAND_ID, ITEM_ID),
    CONSTRAINT FK_03_DEMAND_LINE_HEADER FOREIGN KEY (DEMAND_ID)
        REFERENCES TEAM_03_DEMAND (DEMAND_ID),
    CONSTRAINT FK_03_DEMAND_LINE_ITEM FOREIGN KEY (ITEM_ID)
        REFERENCES TEAM_03_ITEM (ITEM_ID),
    CONSTRAINT CK_03_DEMAND_LINE_QTY CHECK (REQUESTED_QTY > 0)
);

CREATE TABLE TEAM_03_RFQ_VENDOR (
    RFQ_VENDOR_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1) PRIMARY KEY,
    DEMAND_ID             NUMBER       NOT NULL,
    VENDOR_ID             NUMBER       NOT NULL,
    SENT_DATE             TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    QUOTATION_DUE_DATE    DATE         NOT NULL,
    INVITATION_STATUS     VARCHAR2(20) DEFAULT 'SENT' NOT NULL,
    CONSTRAINT UK_03_RFQ_DEMAND_VENDOR UNIQUE (DEMAND_ID, VENDOR_ID),
    CONSTRAINT FK_03_RFQ_DEMAND FOREIGN KEY (DEMAND_ID)
        REFERENCES TEAM_03_DEMAND (DEMAND_ID),
    CONSTRAINT FK_03_RFQ_VENDOR FOREIGN KEY (VENDOR_ID)
        REFERENCES TEAM_03_VENDOR (VENDOR_ID),
    CONSTRAINT CK_03_RFQ_STATUS CHECK
        (INVITATION_STATUS IN ('SENT', 'VIEWED', 'QUOTED', 'DECLINED', 'EXPIRED'))
);


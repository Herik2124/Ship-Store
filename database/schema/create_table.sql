-- Project Code : AHM_2026_03
-- Database     : Oracle Database 12c or later
-- Purpose      : Ship Store General Utilities Procurement and Vendor Management
--
-- Naming convention: TEAM_03_<TABLE_NAME>
-- This script intentionally does not drop existing objects. Run it in a new schema
-- or remove existing TEAM_03_ objects before running it again. Identity values start
-- at 100 so the explicit sample IDs (1, 2, ...) do not conflict with new records.
--
-- Important business validations to implement in ADF/PLSQL:
-- 1. A quotation can be selected only when it fully covers every demand line.
-- 2. The quotation expected delivery date must be on/before the required date.
-- 3. A vendor can mark DELIVERED only when all order quantities are delivered.
-- 4. A vendor rating can be submitted once, only after PO status is DELIVERED.

--------------------------------------------------------------------------------
-- 1. LOGIN AND MASTER TABLES
--------------------------------------------------------------------------------

CREATE TABLE TEAM_03_APP_USER (
    USER_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1) PRIMARY KEY,
    USERNAME         VARCHAR2(80)  NOT NULL,
    PASSWORD_HASH    VARCHAR2(255) NOT NULL,
    FULL_NAME        VARCHAR2(150) NOT NULL,
    EMAIL            VARCHAR2(150) NOT NULL,
    USER_TYPE        VARCHAR2(20)  NOT NULL,
    USER_STATUS      VARCHAR2(20)  DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT       TIMESTAMP,
    CONSTRAINT UK_03_USER_USERNAME UNIQUE (USERNAME),
    CONSTRAINT UK_03_USER_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_03_USER_TYPE CHECK
        (USER_TYPE IN ('ADMIN', 'SHIP_USER', 'VENDOR_USER')),
    CONSTRAINT CK_03_USER_STATUS CHECK
        (USER_STATUS IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE TEAM_03_SHIP (
    SHIP_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1) PRIMARY KEY,
    APP_USER_ID       NUMBER NOT NULL,
    SHIP_CODE         VARCHAR2(20)  NOT NULL,
    SHIP_NAME         VARCHAR2(150) NOT NULL,
    IMO_NUMBER        VARCHAR2(20),
    SHIP_STATUS       VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT        TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT        TIMESTAMP,
    CONSTRAINT UK_03_SHIP_USER UNIQUE (APP_USER_ID),
    CONSTRAINT UK_03_SHIP_CODE UNIQUE (SHIP_CODE),
    CONSTRAINT UK_03_SHIP_IMO UNIQUE (IMO_NUMBER),
    CONSTRAINT FK_03_SHIP_USER FOREIGN KEY (APP_USER_ID)
        REFERENCES TEAM_03_APP_USER (USER_ID),
    CONSTRAINT CK_03_SHIP_STATUS CHECK
        (SHIP_STATUS IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE TEAM_03_VENDOR (
    VENDOR_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1) PRIMARY KEY,
    APP_USER_ID        NUMBER NOT NULL,
    VENDOR_CODE        VARCHAR2(20)  NOT NULL,
    VENDOR_NAME        VARCHAR2(200) NOT NULL,
    EMAIL              VARCHAR2(150),
    PHONE              VARCHAR2(30),
    ADDRESS            VARCHAR2(500),
    CITY               VARCHAR2(100),
    COUNTRY            VARCHAR2(100),
    VENDOR_STATUS      VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    AVERAGE_RATING     NUMBER(3,2) DEFAULT 0 NOT NULL,
    TOTAL_RATINGS      NUMBER       DEFAULT 0 NOT NULL,
    CREATED_AT         TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT         TIMESTAMP,
    CONSTRAINT UK_03_VENDOR_USER UNIQUE (APP_USER_ID),
    CONSTRAINT UK_03_VENDOR_CODE UNIQUE (VENDOR_CODE),
    CONSTRAINT FK_03_VENDOR_USER FOREIGN KEY (APP_USER_ID)
        REFERENCES TEAM_03_APP_USER (USER_ID),
    CONSTRAINT CK_03_VENDOR_STATUS CHECK
        (VENDOR_STATUS IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT CK_03_VENDOR_AVG_RATING CHECK
        (AVERAGE_RATING BETWEEN 0 AND 5),
    CONSTRAINT CK_03_VENDOR_TOTAL_RATINGS CHECK
        (TOTAL_RATINGS >= 0)
);

CREATE TABLE TEAM_03_ITEM_CATEGORY (
    CATEGORY_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1) PRIMARY KEY,
    CATEGORY_NAME     VARCHAR2(100) NOT NULL,
    DESCRIPTION       VARCHAR2(500),
    STATUS            VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT        TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UK_03_CATEGORY_NAME UNIQUE (CATEGORY_NAME),
    CONSTRAINT CK_03_CATEGORY_STATUS CHECK
        (STATUS IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE TEAM_03_ITEM (
    ITEM_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1) PRIMARY KEY,
    ITEM_CODE         VARCHAR2(30)  NOT NULL,
    ITEM_NAME         VARCHAR2(200) NOT NULL,
    CATEGORY_ID       NUMBER        NOT NULL,
    UNIT_OF_MEASURE   VARCHAR2(20)  NOT NULL,
    SPECIFICATION     VARCHAR2(1000),
    ACTIVE_FLAG       CHAR(1) DEFAULT 'Y' NOT NULL,
    CREATED_AT        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT        TIMESTAMP,
    CONSTRAINT UK_03_ITEM_CODE UNIQUE (ITEM_CODE),
    CONSTRAINT FK_03_ITEM_CATEGORY FOREIGN KEY (CATEGORY_ID)
        REFERENCES TEAM_03_ITEM_CATEGORY (CATEGORY_ID),
    CONSTRAINT CK_03_ITEM_ACTIVE CHECK (ACTIVE_FLAG IN ('Y', 'N'))
);

